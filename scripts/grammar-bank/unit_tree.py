    here = units_of(level, chapter_no)
    if old in here:
        return old
    got = SAME.get(old)
    if got and got in here:
        return got
    # 「형용사」는 단원마다 가리키는 자리가 다르다
    if old == "형용사":
        for want in ("형용사", "형용사의 쓰임"):
            if want in here:
                return want
    return None

