def level_of(book):
    # 「Grammar_Inside_Level_1」 과 「Grammar_Inside_Starter」 를 가른다.
    # Starter 를 먼저 보지 않으면 Level_ 쪽이 먼저 걸리는 일은 없지만, 이름이
    # 바뀌어도 흔들리지 않게 긴 조각부터 본다.
    for key in sorted(LEVEL, key=len, reverse=True):
        if key in str(book):
            return key
    return None


def place(book, chapter_no, unit=None):
    """(레벨, 은행 단원 번호, 은행 단원 이름). 못 찾으면 None."""
    key = level_of(book)
    if key is None or not chapter_no:
        return None
    for word, spot in SPLIT.get((key, chapter_no), []):
        if word in str(unit or ""):
            return spot
    return MAP.get((key, chapter_no))
