# -*- coding: utf-8 -*-
"""열중 16강 문법 단원을 문법 은행 목차로 보낸다.

LEVEL 1·2·3 이 중1·중2·중3 이다. 한 Chapter 에 두 강(UNIT)을 묶어 놓아 은행의
단원 하나로 바로 보낼 수 없는 곳이 많다(「명사, 관사, 대명사」 → 명사와 관사 /
대명사). 그래서 **강 이름**을 먼저 보고, 없으면 단원 번호로 보낸다.

내신 적중 테스트·문법정리 OX·서술형 내공 Up 은 단원 전체를 아우르므로 강 이름이
없다. 그때는 단원 번호의 기본 자리로 보낸다.
"""
LEVEL = {"LEVEL 1": 1, "LEVEL 2": 2, "LEVEL 3": 3}

# (레벨, 단원 번호) → 기본 자리
MAP = {
    # ── LEVEL 1 → 중1 ──
    (1, 1): (1, 1, "be동사"),
    (1, 2): (1, 3, "동사의 시제"),
    (1, 3): (1, 5, "명사와 관사"),
    (1, 4): (1, 9, "형용사와 부사"),
    (1, 5): (1, 4, "조동사"),
    (1, 6): (1, 10, "to부정사"),
    (1, 7): (1, 7, "문장의 형식"),
    (1, 8): (1, 14, "전치사"),
    # ── LEVEL 2 → 중2 ──
    (2, 1): (2, 1, "문장의 형식"),
    (2, 2): (2, 2, "시제"),
    (2, 3): (2, 3, "부정사[1]"),
    (2, 4): (2, 7, "조동사"),
    (2, 5): (2, 9, "수동태와 능동태"),
    (2, 6): (2, 8, "관계사"),
    (2, 7): (2, 11, "비교구문"),
    (2, 8): (2, 12, "대명사와 수일치"),
    # ── LEVEL 3 → 중3 ──
    (3, 1): (3, 3, "완료시제"),
    (3, 2): (3, 1, "부정사"),
    (3, 3): (3, 10, "분사구문"),
    (3, 4): (3, 5, "수동태"),
    (3, 5): (3, 4, "조동사"),
    (3, 6): (3, 6, "관계사"),
    (3, 7): (3, 9, "접속사"),
    (3, 8): (3, 11, "일치와 화법"),
}

# 강 이름에 이 말이 들면 그 자리로 보낸다 (묶음 단원을 가른다)
SPLIT = {
    (1, 1): [("일반동사", (1, 2, "일반동사"))],
    (1, 2): [("진행", (1, 3, "동사의 시제")), ("미래", (1, 3, "동사의 시제"))],
    (1, 3): [("대명사", (1, 6, "대명사"))],
    (1, 4): [("비교", (1, 12, "비교구문"))],
    (1, 6): [("동명사", (1, 11, "동명사"))],
    (1, 7): [("문장의 종류", (1, 8, "다양한 문장의 형태"))],
    (1, 8): [("접속사", (1, 13, "접속사"))],
    (2, 3): [("동명사", (2, 5, "동명사")), ("분사", (2, 6, "분사"))],
    (2, 8): [("접속사", (2, 14, "접속사[1]"))],
    (3, 2): [("동명사", (3, 2, "동명사"))],
    (3, 7): [("가정법", (3, 7, "가정법"))],
    (3, 8): [("비교", (3, 8, "비교구문")), ("특수", (3, 12, "특수구문"))],
}


def level_of(book):
    for key, lv in LEVEL.items():
        if key in str(book):
            return lv
    return None


def place(book, chapter_no, unit=None, said=None):
    """(레벨, 은행 단원 번호, 은행 단원 이름). 못 찾으면 None.

    강 이름이 있으면 그것으로 가른다. 시험·서술형 문항은 단원 전체를 아우르므로
    강 이름이 없다 — 그때는 해설·이름표에 적힌 문법 이름을 보고 가린다. 그래도
    모르면 단원의 기본 자리로 보낸다.
    """
    lv = level_of(book)
    if lv is None or not chapter_no:
        return None
    ways = SPLIT.get((lv, chapter_no), [])
    for word, spot in ways:
        if word in str(unit or ""):
            return spot
    base = MAP.get((lv, chapter_no))
    if not ways or not said or unit:
        return base
    # 갈림길마다 제 이름이 글에 몇 번 나오는지 센다
    text = str(said)
    best, score = base, (text.count(base[2]) if base else 0)
    for word, spot in ways:
        got = text.count(word) + text.count(spot[2])
        if got > score:
            best, score = spot, got
    return best
