def level_of(book):
    for key, lv in LEVEL.items():
        if key in str(book):
            return lv
    return None


def place(book, chapter_no, unit=None):
    lv = level_of(book)
    if lv is None or not chapter_no:
        return None
    seat = (lv, int(chapter_no))
    said = str(unit or "")
    for pattern, spot in SPLIT.get(seat, []):
        if re.search(pattern, said):
            return spot
    return MAP.get(seat)
