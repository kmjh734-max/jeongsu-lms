"""고등 어법·서술형 교사용의 단원을 문법 은행 고등 목차로 보낸다.

교재는 단원을 15가지로 잘게 갈라 놓았고(「관계부사·복합관계사」처럼 둘을 묶은
것도 있다), 은행 고등 목차는 12가지다. 아래 표로 보낸다.

「동사의 시제와 태」만은 표 하나로 정해지지 않는다 — 시제와 수동태가 함께
들어 있어, 문항에 수동태 꼴이 보이면 수동태 쪽으로 보낸다.
"""
import re

LEVEL = 4

MAP = {
    "to부정사": (1, "부정사"),
    "동명사": (2, "동명사"),
    "동사의 시제와 태": (3, "완료시제"),
    "조동사": (4, "조동사"),
    "관계대명사": (6, "관계사"),
    "관계부사·복합관계사": (6, "관계사"),
    "가정법": (7, "가정법"),
    "비교": (8, "비교구문"),
    "상관 접속사·명사절 접속사": (9, "접속사"),
    "부사절 접속사": (9, "접속사"),
    "분사구문": (10, "분사구문"),
    "주의해야 할 분사구문": (10, "분사구문"),
    "수 일치": (11, "일치와 화법"),
    "5형식": (12, "특수구문"),
    "도치·강조·생략": (12, "특수구문"),
}

# 「be동사 + 과거분사」 꼴이 보이면 수동태다
PASSIVE = re.compile(
    r"\b(am|is|are|was|were|be|been|being|get|got)\s+\w+(ed|en|wn|ne|de|lt|ght)\b", re.I)


def place(chapter, text):
    """(레벨, 은행 단원 번호, 은행 단원 이름). 못 찾으면 None."""
    hit = MAP.get(str(chapter or "").strip())
    if not hit:
        return None
    if hit == (3, "완료시제") and (PASSIVE.search(text or "") or "수동태" in (text or "")):
        hit = (5, "수동태")
    return (LEVEL,) + hit
