def place(title):
    """(레벨, 은행 단원 번호, 은행 단원 이름). 못 찾으면 None."""
    name = str(title or "").strip()
    if not name:
        return None
    for word, spot in RULES:
        if word in name:
            return (LEVEL,) + spot
    return None
