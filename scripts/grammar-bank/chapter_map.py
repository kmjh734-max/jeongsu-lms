def level_of(book_name):
    for key, lv in BOOK_LEVEL.items():
        if key in book_name:
            return lv
    return None


def place(book_name, chapter_title):
    """교재 단원 → (레벨, 단원 번호, 단원 이름). 못 찾으면 None."""
    lv = level_of(book_name)
    if lv is None or not chapter_title:
        return None
    title = chapter_title.strip()
    hit = CHAPTER_MAP.get((lv, title))
    if hit:
        return lv, hit[0], hit[1]
    # 「관계사 1」처럼 뒤에 붙은 번호는 교재가 갈래를 쪼갠 자국이다.
    # 표에 그 꼴이 없으면 번호를 떼고 다시 찾는다.
    bare = re.sub(r"\s*\d+$", "", title).strip()
    if bare != title:
        hit = CHAPTER_MAP.get((lv, bare))
        if hit:
            return lv, hit[0], hit[1]
    return None
