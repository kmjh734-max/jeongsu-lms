# POINT 제목으로 가르는 자리 — 앞에서부터 들어맞는 첫 줄로 보낸다
SPLIT = {
    (1, 1): [(r"be동사", (1, 1, "be동사"))],
    (1, 5): [(r"There\s*is", (1, 8, "다양한 문장의 형태"))],
    (2, 6): [(r"수량\s*표현", (2, 13, "형용사와 명사의 수량표현"))],
    (2, 7): [(r"의문대명사", (2, 16, "부가의문문과 간접의문문"))],
    (2, 11): [(r"의문사\s*\+\s*to부정사|too\s*~?\s*to|enough\s*to|진주어|진목적어|의미상",
               (2, 4, "부정사[2]"))],
    (2, 12): [(r"현재분사", (2, 6, "분사"))],
    (2, 16): [(r"시간|이유|조건|양보|목적|결과", (2, 15, "접속사[2]"))],
    (3, 1): [(r"미래", (2, 2, "시제"))],
    (3, 12): [(r"간접의문문", (2, 16, "부가의문문과 간접의문문"))],
}


def level_of(book):
    for key, lv in LEVEL.items():
        if key in str(book):
            return lv
    return None


def place(book, chapter_no, unit=None):
    lv = level_of(book)
    if lv is None or not chapter_no:
        return None
    seat = (lv, int(chapter_no))
    said = str(unit or "")
    for pattern, spot in SPLIT.get(seat, []):
        if re.search(pattern, said, re.I):
            return spot
    return MAP.get(seat)
