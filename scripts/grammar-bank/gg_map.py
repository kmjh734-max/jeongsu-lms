# 한 단원이 두 갈래에 걸치는 데 — (단계, 단원번호): [(첫 쪽, 끝 쪽, 보낼 자리)]
# 쪽은 차례에 적힌 UNIT 쪽이다. 「실력 다지기」는 UNIT 바로 다음 쪽에 붙는다.
PAGES = {
    # L2 CHAPTER 02 to부정사 — UNIT 08 가주어·의미상의 주어(32), UNIT 09
    # enough to·too ~ to(34) 는 은행에서 「부정사[2]」다
    (2, 2): [(32, 39, (2, 4, "부정사[2]"))],
    # L2 CHAPTER 08 접속사 — UNIT 23 시간(98), 24 이유·결과(100), 25 조건·양보(102)
    (2, 8): [(98, 107, (2, 15, "접속사[2]"))],
}


def level_of(book):
    for key, lv in LEVEL.items():
        if key in str(book):
            return lv
    return None


def place(book, chapter, unit=None, chapter_no=None, page=None):
    lv = level_of(book)
    if lv is None:
        return None
    if lv in (2, 3) and chapter_no:
        for lo, hi, spot in PAGES.get((lv, int(chapter_no)), []):
            if page and lo <= int(page) <= hi:
                return spot
        return BY_NO.get((lv, int(chapter_no)))
    name = str(chapter or "").strip()
    for word, spot in SPLIT.get((lv, name), []):
        if word in str(unit or ""):
            return spot
    return MAP.get((lv, name))
