def settle(level, chapter, name):
    """교재가 쓴 세부 이름 → 이 단원에서 쓸 이름. 쓸 데가 없으면 None."""
    if not name:
        return None
    key = (level, chapter, name.strip())
    if key in STRAY:
        return None
    if key in SEND:
        return SEND[key]
    if name.strip() in UNITS.get((level, chapter), []):
        return name.strip()
    return None
