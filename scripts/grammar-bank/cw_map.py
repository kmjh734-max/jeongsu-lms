# 둘을 묶어 놓은 단원 — Unit 이름에 이 말이 있으면 저쪽으로 보낸다
SPLIT = {
    (1, "to부정사와 동명사"): [("동명사", (11, "동명사"))],
    (1, "형용사, 부사, 비교"): [("비교", (12, "비교구문"))],
}


def level_of(book):
    for key, lv in LEVEL.items():
        if key in str(book):
            return lv
    return None


def place(book, chapter, unit):
    """(레벨, 은행 단원 번호, 은행 단원 이름). 못 찾으면 None."""
    lv = level_of(book)
    if lv is None or not chapter:
        return None
    title = str(chapter).strip()
    for word, spot in SPLIT.get((lv, title), []):
        if word in str(unit or ""):
            return (lv,) + spot
    hit = MAP.get((lv, title))
    return (lv,) + hit if hit else None
