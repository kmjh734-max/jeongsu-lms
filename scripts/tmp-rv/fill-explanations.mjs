const ANSWER_FIXES = { 33: 4 };

if (EXPLANATIONS.length !== items.length) {
  throw new Error(`해설 ${EXPLANATIONS.length}개 · 문항 ${items.length}개 — 수가 다릅니다`);
}

let exp = 0;
let ins = 0;
let ans = 0;
for (let i = 0; i < items.length; i++) {
  const q = items[i];
  const patch = { explanation: EXPLANATIONS[i] };
  exp += 1;
  if (INSTRUCTION_FIXES[i]) {
    patch.instruction = INSTRUCTION_FIXES[i];
    ins += 1;
    console.log(`지시문 ${q.set} ${q.no}번: ${q.instruction} → ${patch.instruction}`);
  }
  if (ANSWER_FIXES[i]) {
    patch.correct_answer = ANSWER_FIXES[i];
    ans += 1;
    console.log(`정답 ${q.set} ${q.no}번: ${q.answer} → ${patch.correct_answer}`);
  }
  if (apply) {
    const { error } = await admin.from("listening_questions").update(patch).eq("id", q.id);
    if (error) throw new Error(`${q.set} ${q.no}번: ${error.message}`);
  }
}

