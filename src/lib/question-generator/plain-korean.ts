/**
 * 해설 말투를 「~다」 평서형으로 고른다.
 *
 * 선생님 지적(2026-09-29): 해설지에 "맞다."와 "맞습니다."가 섞여 나와 학생이 헷갈려한다.
 * 프롬프트로도 시키지만 모델이 이따금 존댓말로 돌아가므로, 내보내기 전에 코드가 다듬는다.
 *
 * 이미 만들어 둔 해설은 건드리지 않는다(선생님 결정: 앞으로 만드는 것부터면 된다).
 * 그래서 만들 때 한 번만 거치고, 보여 줄 때는 저장된 글을 그대로 쓴다.
 *
 * 문장을 고쳐 쓰지 않는다 — 어미만 바꾼다. 뜻이 달라질 만한 것은 건드리지 않는다.
 */

/** 긴 것부터 바꾼다(습니다까 → 습니다 순서로 먹히지 않게) */
const ENDINGS: Array<[RegExp, string]> = [
  // 물음표로 끝나는 말은 그대로 둔다(해설에 드물지만 있으면 뜻이 바뀐다)
  [/하였습니다/g, "하였다"],
  [/되었습니다/g, "되었다"],
  [/이었습니다/g, "이었다"],
  [/있었습니다/g, "있었다"],
  [/없었습니다/g, "없었다"],
  [/했습니다/g, "했다"],
  [/왔습니다/g, "왔다"],
  [/갔습니다/g, "갔다"],
  [/봤습니다/g, "봤다"],
  [/쐈습니다/g, "쐈다"],
  [/([가-힣])었습니다/g, "$1었다"],
  [/([가-힣])았습니다/g, "$1았다"],
  [/([가-힣])였습니다/g, "$1였다"],
  [/입니다/g, "이다"],
  [/입니까/g, "인가"],
  [/합니다/g, "한다"],
  [/됩니다/g, "된다"],
  [/옵니다/g, "온다"],
  [/갑니다/g, "간다"],
  [/납니다/g, "난다"],
  [/삽니다/g, "산다"],
  [/봅니다/g, "본다"],
  [/씁니다/g, "쓴다"],
  [/듭니다/g, "든다"],
  [/큽니다/g, "크다"],
  [/깁니다/g, "긴다"],
  [/있습니다/g, "있다"],
  [/없습니다/g, "없다"],
  [/같습니다/g, "같다"],
  [/많습니다/g, "많다"],
  [/적습니다/g, "적다"],
  [/맞습니다/g, "맞다"],
  [/틀립니다/g, "틀리다"],
  [/아닙니다/g, "아니다"],
  [/쉽습니다/g, "쉽다"],
  /*
   * 「~습니다」를 한꺼번에 「~다」로 바꾸면 동사가 어색해진다(않습니다 → 않다).
   * 해설에 자주 나오는 동사는 먼저 「~는다」로 바꿔 둔다.
   */
  [/않습니다/g, "않는다"],
  [/받습니다/g, "받는다"],
  [/읽습니다/g, "읽는다"],
  [/찾습니다/g, "찾는다"],
  [/남습니다/g, "남는다"],
  [/붙습니다/g, "붙는다"],
  [/믿습니다/g, "믿는다"],
  [/얻습니다/g, "얻는다"],
  [/듣습니다/g, "듣는다"],
  [/묻습니다/g, "묻는다"],
  [/넣습니다/g, "넣는다"],
  [/놓습니다/g, "놓는다"],
  [/갖습니다/g, "갖는다"],
  [/맡습니다/g, "맡는다"],
  [/잊습니다/g, "잊는다"],
  [/웃습니다/g, "웃는다"],
  [/어렵습니다/g, "어렵다"],
  [/자연스럽습니다/g, "자연스럽다"],
  [/([가-힣])ㅂ니다/g, "$1다"],
  // 남은 「~습니다」는 형용사 어간으로 보고 「~다」로 끊는다
  [/([가-힣])습니다/g, "$1다"],
  // 부드러운 존댓말도 함께
  [/해요(?=[.,!?)\s]|$)/g, "한다"],
  [/이에요(?=[.,!?)\s]|$)/g, "이다"],
  [/예요(?=[.,!?)\s]|$)/g, "이다"],
  [/돼요(?=[.,!?)\s]|$)/g, "된다"],
  [/있어요(?=[.,!?)\s]|$)/g, "있다"],
  [/없어요(?=[.,!?)\s]|$)/g, "없다"],
  [/맞아요(?=[.,!?)\s]|$)/g, "맞다"],
];

/** 해설·풀이를 「~다」 평서형으로 다듬는다. 영어와 숫자는 건드리지 않는다. */
export function plainKorean(text: string): string {
  let out = String(text ?? "");
  if (!out) return out;
  for (const [re, to] of ENDINGS) out = out.replace(re, to);
  return out;
}
