/*
 * 내용일치·불일치 전용(2026-10-04, 전수조사 1,248문항 + ChatGPT 의견).
 * 공통 지침(choiceCraftCommonRules)의 「오답은 핵심 관계만 미세하게 틀리게」는 내용불일치에서 참이어야 할
 * 네 보기에 흠을 넣었고(불량 18건 대부분), 「두 개념 결합」 기법은 없는 인과를 만들었다. 「오답」 대신
 * 참 보기·거짓 보기로 나눠 지시한다.
 */
export function factChoiceCraft(isFalseType: boolean, en: boolean): string {
  return `사실 보기 제작 (내용${isFalseType ? "불일치" : "일치"}):
- 이 문항은 ${isFalseType ? "거짓 보기 1개(정답) + 참 보기 4개" : "참 보기 1개(정답) + 거짓 보기 4개"}로 만든다.
- 참 보기: 원문의 사실을 그대로 지킨다. 문장 구조와 일반 표현만 자연스럽게 바꾼다.
  사람·사물의 이름, 숫자·단위, 조건, 정도(every/never/some …), 시점, 누가 한 말·생각인지는 바꾸지 않는다.
- 거짓 보기: 원문의 사실 하나에서 의미 요소 <b>하나</b>(주체·행동·대상·수량·조건·시점·주장한 사람·방향)만 바꾼다.
  원문 문장과 함께 놓으면 둘 다 참일 수 없어야 한다(원문으로 분명히 반박된다).
  「지문에 언급 없음」, 지문에 없는 비교·시점·인과·사람을 덧붙여 거짓을 만들지 않는다 — 그것은 반박이 아니라 판단 불가다.
- 거짓 보기는 대충 읽은 학생이 참으로 믿을 만해야 한다. 낱말 하나를 반의어로 뒤집는 것(increase→decrease, 가깝게→멀어지게)은
  한 문항에 하나까지만. 나머지는 주체·대상 바꾸기, 지문의 다른 수치·이름·조건과 섞기, 누가 한 말인지 바꾸기, 두 대상의 관계 바꾸기로 만든다.
  문장 자체가 앞뒤가 안 맞아 지문 없이 지워지는 보기(「데워서 영하로」)는 쓰지 않는다.
- 다섯 보기는 서로 다른 사실을 다룬다(같은 사실을 참·거짓으로 되풀이하지 않는다). 지문 앞·중간·뒤를 고루 다룬다.
- 보기끼리 기대지 않는다(that ideal, 그다음, 결국 금지). 보기 하나만 읽어도 무엇을 말하는지 안다 —
  「이 과정에서」「이러한 시도는」「그들은」「다른 일부 종은」처럼 가리키는 대상이 보기 밖에 있는 말로 시작하지 않고 대상을 이름으로 쓴다.
- 정답이 표시 나지 않게: 정답만 극단어·정답만 글의 요지·정답만 유난히 길거나 짧음 금지. 다른 보기를 그대로 뒤집은 보기 금지.
- ${en ? "자연스러운 영어 시험체" : "자연스러운 한국어 시험체"}.`;
}

