const YEARS: Record<number, YearHolidays> = {
  2026: HOLIDAYS_2026,
  2027: HOLIDAYS_2027,
};

/** 적어 둔 해인지 — 아직 안 적은 해는 표시를 못 한다 */
export function hasHolidayTable(year: number): boolean {
  return year in YEARS;
}

/** 이 날이 공휴일이면 이름, 아니면 빈 문자열 */
export function holidayNameOf(iso: string): string {
  const year = Number(iso.slice(0, 4));
  return YEARS[year]?.[iso] ?? "";
}

/** 그 달의 공휴일 — { "2026-09-25": "추석", … } */
export function monthHolidays(year: number, month: number): Record<string, string> {
  const table = YEARS[year];
  if (!table) return {};
  const head = `${year}-${String(month).padStart(2, "0")}-`;
  return Object.fromEntries(Object.entries(table).filter(([d]) => d.startsWith(head)));
}
