/**
 * 파생어가 아닌 짝(낱말>꼴). 윌링어학원 단어장 370낱말을 하나하나 읽어 골랐다(2026-10-30) — 뿌리가 다른 말(concerto → concerted),
 * 지어낸 말(perspectively), 변화형(lacks)을 모델이 파생어로 주어 시험 문항이 틀리게 나왔다.
 */
const BAD_FORM_PAIRS = new Set([
  "affect>effect",
  "award-winning>awarded",
  "capture>captivating",
  "chew>chewer",
  "cling>clingingness",
  "concern>concernment",
  "concerto>concerted",
  "council>counsel",
  "criterion>critical",
  "criterion>critically",
  "device>deviceful",
  "disability>disabuse",
  "discard>discards",
  "fade>fader",
  "flourish>flourisher",
  "formation>formal",
  "former>form",
  "hardship>hardly",
  "increase>increaser",
  "instance>instant",
  "instance>instantly",
  "intention>intended",
  "lack>lacks",
  "magnificent>magnify",
  "major>majorly",
  "majority>majorly",
  "mean>meaningly",
  "minor>minimize",
  "monitor>monitors",
  "perspective>perspectively",
  "possible>positively",
  "prime>primer",
  "prominent>promote",
  "quality>qualify",
  "revolutionary>revolve",
  "rise>riser",
  "solution>solving",
  "sought>seeking",
  "subordinate>subordinately",
  "tale>told",
  "tend>tender",
  "term>terminal",
  "term>terminate",
  "verse>versatile",
  "verse>versatilely",
  "version>versatile",
  "wild>wilder",
]);

export function isBadWordForm(word: string, form: string): boolean {
  return BAD_FORM_PAIRS.has(`${word.trim().toLowerCase()}>${form.trim().toLowerCase()}`);
}
